# B. Klasifikasi Masalah (Volume Problem vs Margin Problem)
# Logika Diagnostik:
# - Margin Problem: Sales tinggi / Qty banyak, tetapi Margin negatif (biasanya karena diskon terlalu boros).
# - Volume Problem: Margin positif / wajar, tetapi Sales dan Qty sangat kecil sehingga nominal profit tidak tumbuh.
def diagnose_problem(row, median_sales):
    if row['Total_Profit'] < 0:
        if row['Total_Sales'] >= median_sales:
            return "Severe Margin Problem (High Sales, Deep Loss)"
        else:
            return "Margin Problem (Loss despite low sales)"
    else:
        if row['Total_Sales'] < median_sales and row['Profit_Margin_%'] > 10:
            return "Volume Problem (Good Margin, Low Sales Volume)"
        return "Healthy / Profitable"

median_sales = product_subcat['Total_Sales'].median()
