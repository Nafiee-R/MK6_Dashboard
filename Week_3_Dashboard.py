def calculate_kpi(df, group_cols):
    """Menghitung ringkasan metrik finansial teragregasi."""
    summary = (
        df.groupby(group_cols)
        .agg(
            Total_Sales=('Sales', 'sum'),
            Total_Profit=('Profit', 'sum'),
            Total_Qty=('Quantity', 'sum'),
            Avg_Discount=('Discount', 'mean'),
            Order_Count=('Order ID', 'nunique') if 'Order ID' in df.columns else ('Sales', 'count')
        )
        .reset_index()
    )
    summary['Profit_Margin_%'] = (summary['Total_Profit'] / summary['Total_Sales']) * 100
    summary['Avg_Discount_%'] = summary['Avg_Discount'] * 100
    return summary

